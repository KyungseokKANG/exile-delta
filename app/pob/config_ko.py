def label(text: str, kind: str = "") -> str:
    """옵션 라벨 번역. kind == 'label' 이면 스킬 소제목(젬 이름)."""
    t = (text or "").strip().rstrip(":").strip()
    if t in LABELS:
        return LABELS[t]
    names = _load_names()
    if kind == "label":
        if t in names:
            return names[t]
        if f"{t} Support" in names:
            return names[f"{t} Support"]
    return names.get(t, t)


